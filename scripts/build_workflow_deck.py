FIXED_TITLES = {
    "title_slide": "From two matrices to one network",
    "glossary_slide": "The words used on every slide",
    "summary_slide": "Summary — four routes, one destination",
}


def build(out_pptx: Path | None = None):
    prs = Presentation()
    prs.slide_width = Inches(SW)
    prs.slide_height = Inches(SH)
    entries = []
    for i, (fn, kw) in enumerate(SLIDES, 1):
        note = kw.pop("note")
        s = fn(prs, i, note=note, **kw)
        s.notes_slide.notes_text_frame.text = note
        title = kw.get("title") or FIXED_TITLES.get(fn.__name__, "Untitled")
        entries.append({"title": title, "eyebrow": kw.get("eyebrow"),
                        "body": md_for(fn, kw), "note": note})
    if out_pptx is not None:
        prs.save(out_pptx)
    return prs, entries


def write_notes(entries, out_md: Path):
    n = len(entries)
    lines = [
        "# Deck notes — from two matrices to a gene regulatory network", "",
        f"{n} slides. One block per way: the blocks are the argument, and they all have the "
        "same shape.", "",
        "Deck order: title → vocabulary → the four ways at a glance → **for each way**: one "
        "overview slide (the steps, with what goes in and what comes out of each), then one "
        "slide of methods and one slide of checks per step → choosing between the ways → "
        "grading the route on simulated data → the gates → run order → summary.", "",
        "Each slide below gives the text that goes on the slide, then the speaker notes. "
        "Generated by `scripts/build_workflow_deck.py`; edit that, not this file.", "",
        "---", ""]

    current_way = None
    for i, e in enumerate(entries, 1):
        way = None
        if e["eyebrow"] and re.fullmatch(r"WAY \d+", e["eyebrow"].strip()):
            way = e["eyebrow"].strip().title()
        if re.match(r"^Way \d+ — ", e["title"]):
            way = e["title"].split(" — ")[0]
        if way and way != current_way:
            current_way = way
            lines += [f"# {way}", ""]

        head = f"## Slide {i} — {e['title']}"
        lines += [head, ""]
        if e["eyebrow"]:
            lines += [f"`{e['eyebrow']}`", ""]
        lines += ["**On the slide**", "", e["body"], "", "**Speaker notes**", "",
                  "\n".join("> " + ln if ln.strip() else ">" for ln in e["note"].split("\n")),
                  "", "---", ""]

    out_md.write_text("\n".join(lines), encoding="utf-8")


def md_only(out_md: Path):
    """Build the content and write the notes document without touching the .pptx."""
    _, entries = build(None)
    write_notes(entries, out_md)
    return len(entries)


