"""Build reports/pipeline-workflow-design.pptx and reports/pipeline-workflow-deck-notes.md.

Organisation:
    front matter       title · vocabulary · the four ways at a glance
    one block per way  overview (steps, what goes in, what comes out)
                       -> for each step: one slide of methods, one slide of checks
    back matter        choosing · simulation · gates · run order · summary

Both outputs come from this one script: the deck is built first, then the notes
markdown is generated by walking the finished slides, so the two cannot drift.

Geometry is checked as we build (estimated text height per table cell vs the row
height allotted). Any line printed as WARN means a cell is likely to overflow.
"""

