# ---------------------------------------------------------------- primitives
def _tf(shape, wrap=True):
    tf = shape.text_frame
    tf.word_wrap = wrap
    tf.margin_left = Inches(0.02)
    tf.margin_right = Inches(0.02)
    tf.margin_top = Inches(0.02)
    tf.margin_bottom = Inches(0.02)
    return tf


def textbox(slide, left, top, width, height, *, anchor=MSO_ANCHOR.TOP):
    tb = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    tf = _tf(tb)
    tf.vertical_anchor = anchor
    return tf


def para(tf, text, *, size=14, bold=False, color=INK, italic=False, space_after=4,
         align=PP_ALIGN.LEFT, first=False, line=1.0):
    p = tf.paragraphs[0] if first else tf.add_paragraph()
    p.alignment = align
    p.space_after = Pt(space_after)
    p.line_spacing = line
    r = p.add_run()
    r.text = text
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.italic = italic
    r.font.name = FONT
    r.font.color.rgb = color
    return p


def rect(slide, left, top, width, height, fill, *, line=None):
    sh = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(left), Inches(top),
                                Inches(width), Inches(height))
    sh.fill.solid()
    sh.fill.fore_color.rgb = fill
    if line is None:
        sh.line.fill.background()
    else:
        sh.line.color.rgb = line
        sh.line.width = Pt(0.75)
    sh.shadow.inherit = False
    return sh


def slide_base(prs, title, kicker=None, accent=C0, number=None, eyebrow=None):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    rect(s, 0, 0, SW, 0.09, accent)
    tw = CW - 3.05 if eyebrow else CW
    need = est_lines(title, tw, 26) * 26 * 1.24 / 72
    if need > 0.52:
        WARNINGS.append(f"title wraps onto a second line ({len(title)} chars): {title!r}")
    tf = textbox(s, ML, 0.26, tw, 0.66)
    para(tf, title, size=26, bold=True, color=INK, first=True, space_after=0)
    if kicker:
        kf = textbox(s, ML, 0.94, CW, 0.46)
        para(kf, kicker, size=13, color=MUTED, italic=True, first=True, space_after=0)
    if eyebrow:
        ef = textbox(s, SW - ML - 2.95, 0.34, 2.95, 0.30)
        para(ef, eyebrow, size=9.5, bold=True, color=accent, align=PP_ALIGN.RIGHT,
             first=True, space_after=0)
    rect(s, ML, 1.46, CW, 0.012, RULE)
    if number is not None:
        nf = textbox(s, SW - ML - 0.9, SH - 0.42, 0.9, 0.28)
        para(nf, str(number), size=9.5, color=FAINT, align=PP_ALIGN.RIGHT, first=True,
             space_after=0)
    return s


def strip(slide, top, text, *, accent, label=None, height=0.52):
    """Coloured summary bar (gate / key point / caveat)."""
    rect(slide, ML, top, CW, height, accent)
    tf = textbox(slide, ML + 0.14, top + 0.02, CW - 0.28, height - 0.04,
                 anchor=MSO_ANCHOR.MIDDLE)
    if label:
        p = tf.paragraphs[0]
        p.space_after = Pt(0)
        r = p.add_run()
        r.text = label + "  "
        r.font.size = Pt(11.5)
        r.font.bold = True
        r.font.name = FONT
        r.font.color.rgb = WHITE
        r2 = p.add_run()
        r2.text = text
        r2.font.size = Pt(11.5)
        r2.font.name = FONT
        r2.font.color.rgb = WHITE
    else:
        para(tf, text, size=11.5, color=WHITE, first=True, space_after=0)
    return top + height


def line(slide, top, text, *, size=10.5, color=MUTED, italic=True):
    n = est_lines(text, CW, size)
    h = n * size * 1.24 / 72 + 0.04
    tf = textbox(slide, ML, top, CW, h)
    para(tf, text, size=size, color=color, italic=italic, first=True, space_after=0)
    if n > 2:
        WARNINGS.append(f"tail runs to {n} lines: {text[:50]!r}")
    return top + h


def est_lines(text, width_in, size):
    cpl = max(8, int((width_in - 0.20) * 72 / (size * 0.50)))
    lines = 0
    for chunk in str(text).split("\n"):
        lines += max(1, math.ceil(len(chunk) / cpl))
    return lines


def table(slide, rows, col_w, top, *, accent, head_size=11, body_size=10.5,
          head_h=0.42, pad=0.10, first_col_bold=False, first_col_color=None,
          total_width=None):
    """rows[0] is the header. Returns bottom edge in inches."""
    nrows, ncols = len(rows), len(rows[0])
    tw = total_width if total_width else sum(col_w)
    heights = []
    for i, row in enumerate(rows):
        size = head_size if i == 0 else body_size
        need = 0.0
        for j, cell in enumerate(row):
            need = max(need, est_lines(cell, col_w[j], size) * size * 1.22 / 72 + pad)
        heights.append(round(max(head_h if i == 0 else 0.30, need), 2))

    total_h = sum(heights)
    gf = slide.shapes.add_table(nrows, ncols, Inches(ML), Inches(top), Inches(tw),
                                Inches(total_h))
    tbl = gf.table
    for j, w in enumerate(col_w):
        tbl.columns[j].width = Emu(int(Inches(w)))
    for i, h in enumerate(heights):
        tbl.rows[i].height = Emu(int(Inches(h)))

    for i, row in enumerate(rows):
        for j, cell_text in enumerate(row):
            cell = tbl.cell(i, j)
            cell.margin_left = Inches(0.08)
            cell.margin_right = Inches(0.06)
            cell.margin_top = Inches(0.04)
            cell.margin_bottom = Inches(0.04)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.fill.solid()
            cell.fill.fore_color.rgb = accent if i == 0 else (WASH if i % 2 == 0 else WHITE)
            tf = cell.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            p.space_after = Pt(0)
            r = p.add_run()
            r.text = str(cell_text)
            r.font.name = FONT
            if i == 0:
                r.font.size = Pt(head_size)
                r.font.bold = True
                r.font.color.rgb = WHITE
            else:
                r.font.size = Pt(body_size)
                r.font.color.rgb = INK
                if j == 0 and first_col_bold:
                    r.font.bold = True
                    if first_col_color is not None:
                        r.font.color.rgb = first_col_color

    for i, h in enumerate(heights):
        for j in range(ncols):
            size = head_size if i == 0 else body_size
            need = est_lines(rows[i][j], col_w[j], size) * size * 1.22 / 72 + pad
            if need > h + 0.02:
                WARNINGS.append(f"cell overflow r{i}c{j} '{str(rows[i][j])[:34]}' "
                                f"needs {need:.2f} has {h:.2f}")
    return top + total_h


def card(slide, left, top, width, height, *, accent, title, lines, size=11,
         title_size=12.5):
    rect(slide, left, top, width, height, WASH)
    rect(slide, left, top, 0.055, height, accent)
    tf = textbox(slide, left + 0.16, top + 0.09, width - 0.28, height - 0.14)
    para(tf, title, size=title_size, bold=True, color=accent, first=True, space_after=5)
    for ln in lines:
        para(tf, ln, size=size, color=INK, space_after=3)
    return top + height


def chain_strip(s, chain, accent, top=BODY_TOP, height=0.86):
    """chain = [(label, sub), ...] with → between."""
    k = len(chain)
    gap = 0.30
    bw = (CW - gap * (k - 1)) / k
    left = ML
    for i, (label, sub) in enumerate(chain):
        rect(s, left, top, bw, height, WASH)
        rect(s, left, top, bw, 0.045, accent)
        tf = textbox(s, left + 0.13, top + 0.10, bw - 0.26, height - 0.15)
        para(tf, label, size=11.5, bold=True, color=accent, first=True, space_after=2)
        para(tf, sub, size=9.5, color=MUTED, space_after=0)
        if i < k - 1:
            ar = textbox(s, left + bw + 0.01, top + 0.26, gap - 0.02, 0.34)
            para(ar, "→", size=14, bold=True, color=FAINT, align=PP_ALIGN.CENTER,
                 first=True, space_after=0)
        left += bw + gap
    return top + height


def check(bottom, label):
    if bottom > BOTTOM_LIMIT:
        WARNINGS.append(f"{label}: content runs to {bottom:.2f}in (limit {BOTTOM_LIMIT})")


