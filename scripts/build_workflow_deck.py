# ---------------------------------------------------------------- markdown
def _tbl(header, rows):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join(["---"] * len(header)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("\n", " ").strip() for c in r) + " |")
    return "\n".join(out)


def _quote(label, text):
    return f"> **{label}** — {text}" if label else f"> {text}"


def _chain(chain):
    return "  →  ".join(f"**{a}** ({b})" for a, b in chain)


