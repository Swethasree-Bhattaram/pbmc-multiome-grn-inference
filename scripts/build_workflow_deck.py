def title_slide(prs, n, *, note, kicker, chain, strip_text):
    s = slide_base(prs, "From two matrices to one network", None, C0, n)
    kf = textbox(s, ML, 1.02, 11.4, 0.86)
    para(kf, kicker, size=15, color=MUTED, italic=True, first=True, space_after=0)
    chain_strip(s, chain, C0, top=2.10, height=1.00)
    b = strip(s, 3.55, strip_text, accent=C0, label="THE SHAPE OF THE TALK", height=0.62)
    table(s, [["What every way is shown with", "On which slides"],
              ["the steps, and what goes in and comes out of each", "one overview slide per way"],
              ["the methods that exist for each step", "one slide per step"],
              ["how that step is judged, and what a good result looks like", "one slide per step"],
              ["how the ways compare, and how the whole route is graded", "the closing block"]],
          [7.4, 4.4], b + 0.30, accent=C0, body_size=11.5)
    return s


def glossary_slide(prs, n, *, note, rows):
    s = slide_base(prs, "The words used on every slide", None, C0, n)
    kf = textbox(s, ML, 0.94, CW, 0.40)
    para(kf, "Nothing else is assumed. Terms that belong to a single way are defined on that "
             "way's overview slide.", size=12.5, color=MUTED, italic=True, first=True,
         space_after=0)
    rows = [["Term", "Plain meaning"]] + rows
    b = table(s, rows, [3.05, 8.75], 1.56, accent=C0, body_size=10.5,
              first_col_bold=True, total_width=11.80)
    check(b, "glossary")
    return s


def table_slide(prs, n, *, note, accent, title, kicker, eyebrow, header, rows,
                widths, strip_label=None, strip_text=None, tail=None, body_size=11,
                first_col_bold=True):
    s = slide_base(prs, title, kicker, accent, n, eyebrow)
    b = table(s, [header] + rows, widths, BODY_TOP, accent=accent, body_size=body_size,
              first_col_bold=first_col_bold, first_col_color=accent,
              total_width=sum(widths))
    if tail:
        b = line(s, b + 0.16, tail)
    if strip_text:
        b = strip(s, b + 0.20, strip_text, accent=accent, label=strip_label, height=0.60)
    check(b, title)
    return s


def way_overview(prs, n, *, note, accent, way, title, kicker, chain, rows, receives,
                 cards, tail=None):
    s = slide_base(prs, title, kicker, accent, n, eyebrow=f"WAY {way}")
    b = chain_strip(s, chain, accent)
    b = table(s, [["Step", "What goes in", "What comes out"]] + rows,
              [2.00, 5.15, 4.95], b + 0.20, accent=accent, body_size=10.5,
              first_col_bold=True, first_col_color=accent, total_width=12.10)
    b = strip(s, b + 0.18, receives, accent=accent, label="THE GRN RECEIVES", height=0.54)
    cw = (CW - 2 * 0.20) / 3
    for i, (label, text, h) in enumerate(cards):
        card(s, ML + i * (cw + 0.20), b + 0.18, cw, h, accent=accent, title=label,
             lines=[text], size=9.8, title_size=10.5)
    bottom = b + 0.18 + max(c[2] for c in cards)
    if tail:
        bottom = line(s, bottom + 0.08, tail)
    check(bottom, title)
    return s


def step_methods(prs, n, *, note, accent, eyebrow, title, kicker, header, rows, widths,
                 strip_label, strip_text, tail=None, body_size=10.5):
    s = slide_base(prs, title, kicker, accent, n, eyebrow)
    b = table(s, [header] + rows, widths, BODY_TOP, accent=accent, body_size=body_size,
              first_col_bold=True, first_col_color=accent, total_width=sum(widths))
    if tail:
        b = line(s, b + 0.14, tail, size=10)
    b = strip(s, b + 0.16, strip_text, accent=accent, label=strip_label, height=0.62)
    check(b, title)
    return s


def drop_truth(rows):
    """Rows are (metric, what it asks, truth needed, ...); the truth column is not shown."""
    return [[r[0], r[1]] + list(r[3:]) for r in rows]


def step_checks(prs, n, *, note, accent, eyebrow, title, kicker, rows, widths,
                strip_label, strip_text, tail=None, body_size=11.5, header=None):
    header = header or ["Metric", "What it asks", "Good looks like"]
    if header and header[2] == "Truth needed":
        header = header[:2] + header[3:]
    merged = widths[1] + widths[2]
    widths = [widths[0], round(merged * 0.66, 2), widths[3],
              round(widths[4] + merged * 0.34, 2)] if len(widths) == 5 else \
             [widths[0], round(merged * 0.66, 2), round(widths[3] + merged * 0.34, 2)]
    rows = drop_truth(rows)
    s = slide_base(prs, title, kicker, accent, n, eyebrow)
    b = table(s, [header] + rows, widths, BODY_TOP, accent=accent, body_size=body_size,
              first_col_bold=True, first_col_color=accent, total_width=sum(widths))
    if tail:
        b = line(s, b + 0.14, tail, size=10)
    b = strip(s, b + 0.16, strip_text, accent=accent, label=strip_label, height=0.62)
    check(b, title)
    return s


def compact_step(prs, n, *, note, accent, eyebrow, title, kicker, m_header, m_rows,
                 m_widths, card_title, card_lines, strip_label, strip_text, tail=None):
    """Methods on the left, checks on the right — for steps whose method set is short."""
    s = slide_base(prs, title, kicker, accent, n, eyebrow)
    left_w = sum(m_widths)
    b = table(s, [m_header] + m_rows, m_widths, BODY_TOP, accent=accent, body_size=10.5,
              first_col_bold=True, first_col_color=accent, total_width=left_w)
    cl = ML + left_w + 0.34
    cw = SW - ML - cl
    ch = max(1.9, min(b - BODY_TOP, 3.5))
    card(s, cl, BODY_TOP, cw, ch, accent=accent, title=card_title, lines=card_lines,
         size=10, title_size=11)
    bottom = max(b, BODY_TOP + ch)
    if tail:
        bottom = line(s, bottom + 0.14, tail, size=10)
    bottom = strip(s, bottom + 0.16, strip_text, accent=accent, label=strip_label,
                   height=0.62)
    check(bottom, title)
    return s


def mechanism(prs, n, *, note, accent, eyebrow, title, kicker, items, strip_text, tail):
    s = slide_base(prs, title, kicker, accent, n, eyebrow)
    w = (CW - 0.24) / 2
    top = BODY_TOP
    for i, (num, head, body) in enumerate(items):
        col, row = i % 2, i // 2
        x = ML + col * (w + 0.24)
        y = top + row * 1.30
        rect(s, x, y, w, 1.16, WASH)
        rect(s, x, y, 0.055, 1.16, accent)
        tf = textbox(s, x + 0.16, y + 0.10, 0.5, 0.9)
        para(tf, num, size=22, bold=True, color=FAINT, first=True, space_after=0)
        tf2 = textbox(s, x + 0.72, y + 0.10, w - 0.90, 0.98)
        para(tf2, head, size=11.5, bold=True, color=accent, first=True, space_after=3)
        para(tf2, body, size=10, color=INK, space_after=0)
    b = strip(s, top + 2 * 1.30 + 0.16, strip_text, accent=accent, label="VISIBLE SIGNATURE",
              height=0.62)
    b = line(s, b + 0.16, tail, size=10)
    check(b, title)
    return s


def summary_slide(prs, n, *, note, rows, strip_text):
    s = slide_base(prs, "Summary — four routes, one destination", None, C0, n)
